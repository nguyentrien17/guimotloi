/**
 * Validates template library integrity
 * @returns {{ valid: boolean, total: number, categoryCounts: Object, duplicateIds: string[] }}
 */
export function validateTemplateLibrary() {
  const ids = new Set();
  const duplicateIds = [];
  const categoryCounts = {};

  TEMPLATE_CATEGORIES.forEach(c => {
    categoryCounts[c.id] = 0;
  });

  TEMPLATES_100.forEach(t => {
    if (ids.has(t.id)) {
      duplicateIds.push(t.id);
    }
    ids.add(t.id);

    if (categoryCounts[t.category] !== undefined) {
      categoryCounts[t.category]++;
    }
  });

  const valid = duplicateIds.length === 0 && TEMPLATES_100.length >= 100;

  return {
    valid,
    total: TEMPLATES_100.length,
    categoryCounts,
    duplicateIds
  };
}

/**
 * Retrieves a template by ID (with fallback to default)
 * @param {string} id 
 * @returns {Object}
 */
export function getTemplateById(id) {
  return TEMPLATES_100.find(t => t.id === id) || TEMPLATES_100[0];
}

/**
 * Filters templates by category, keyword, and mood
 * @param {Object} options 
 * @returns {Array}
 */
export function filterTemplates({ category = 'all', keyword = '', mood = 'all' } = {}) {
  let result = [...TEMPLATES_100];

  if (category && category !== 'all') {
    result = result.filter(t => t.category === category);
  }

  if (mood && mood !== 'all') {
    result = result.filter(t => t.mood === mood);
  }

  if (keyword && keyword.trim()) {
    const q = keyword.trim().toLowerCase();
    result = result.filter(t => 
      t.name.toLowerCase().includes(q) ||
      t.categoryName.toLowerCase().includes(q) ||
      (t.tags && t.tags.some(tag => tag.toLowerCase().includes(q)))
    );
  }

  return result;
}
